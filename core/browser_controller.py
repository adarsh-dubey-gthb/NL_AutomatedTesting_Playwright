import os
import time
from typing import Optional, Tuple, Dict
from playwright.sync_api import sync_playwright, Playwright, Browser, BrowserContext, Page, TimeoutError as PlaywrightTimeoutError
from models.actions import AgentAction, ActionType, InteractiveElement


class BrowserController:
    """
    Manages Playwright browser lifecycle and executes planned agent actions resiliently.
    """

    def __init__(self, headless: bool = False, timeout_ms: int = 15000, slow_mo: int = 300):
        self.headless = headless
        self.timeout_ms = timeout_ms
        self.slow_mo = slow_mo
        self.playwright: Optional[Playwright] = None
        self.browser: Optional[Browser] = None
        self.context: Optional[BrowserContext] = None
        self.page: Optional[Page] = None

    def start(self):
        """Initializes and launches Playwright Chromium browser."""
        self.playwright = sync_playwright().start()
        self.browser = self.playwright.chromium.launch(
            headless=self.headless,
            slow_mo=self.slow_mo,
            args=["--disable-blink-features=AutomationControlled", "--no-sandbox"]
        )
        self.context = self.browser.new_context(
            viewport={"width": 1366, "height": 768},
            user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36",
            ignore_https_errors=True
        )
        self.page = self.context.new_page()
        self.page.set_default_timeout(self.timeout_ms)

        # Auto-accept JavaScript alerts/confirms
        self.page.on("dialog", lambda dialog: dialog.accept())

    def stop(self):
        """Cleanly terminates browser and context."""
        try:
            if self.context: self.context.close()
            if self.browser: self.browser.close()
            if self.playwright: self.playwright.stop()
        except:
            pass

    def navigate(self, url: str) -> Tuple[bool, str]:
        """Navigates to URL and waits for basic load."""
        if not url.startswith("http://") and not url.startswith("https://"):
            url = "https://" + url

        try:
            self.page.goto(url, wait_until="domcontentloaded", timeout=self.timeout_ms)
            time.sleep(1.5)
            return True, f"Successfully navigated to {self.page.url}"
        except PlaywrightTimeoutError:
            return True, f"Navigation completed (load event timed out, continuing with partial DOM)"
        except Exception as e:
            return False, f"Navigation error: {str(e)}"

    def take_screenshot(self, filepath: str) -> str:
        """Captures a screenshot of the current page state."""
        try:
            os.makedirs(os.path.dirname(filepath), exist_ok=True)
            self.page.screenshot(path=filepath, full_page=False)
            return filepath
        except Exception as e:
            return ""

    def execute_action(self, action: AgentAction, elements_map: Dict[str, InteractiveElement]) -> Tuple[bool, str]:
        """Executes an action generated by the LLM planner."""
        try:
            if action.action == ActionType.NAVIGATE:
                return self.navigate(action.value)

            elif action.action == ActionType.CLICK:
                return self._execute_click(action, elements_map)

            elif action.action == ActionType.FILL:
                return self._execute_fill(action, elements_map)

            elif action.action == ActionType.SELECT_OPTION:
                return self._execute_select(action, elements_map)

            elif action.action == ActionType.PRESS_KEY:
                key = action.value or "Enter"
                self.page.keyboard.press(key)
                time.sleep(1.0)
                return True, f"Pressed key '{key}'"

            elif action.action == ActionType.WAIT:
                wait_sec = float(action.value or "2.0")
                time.sleep(wait_sec)
                return True, f"Waited {wait_sec} seconds"

            elif action.action == ActionType.ASSERT:
                return self._execute_assert(action)

            elif action.action == ActionType.FINISH:
                status = "PASS" if action.test_passed else "FAIL"
                return action.test_passed, f"Test finished with status: {status}. Reason: {action.reasoning}"

            else:
                return False, f"Unknown action type: {action.action}"

        except Exception as e:
            return False, f"Action execution failed: {str(e)}"

    def _execute_click(self, action: AgentAction, elements_map: Dict[str, InteractiveElement]) -> Tuple[bool, str]:
        locator = self._resolve_locator(action, elements_map)
        if not locator:
            return False, f"Could not find element to click for target '{action.element_id or action.selector}'"

        try:
            locator.scroll_into_view_if_needed(timeout=3000)
            locator.click(timeout=5000)
            time.sleep(1.5)
            return True, f"Clicked element [{action.element_id or action.selector}]"
        except Exception as e:
            try:
                locator.click(force=True, timeout=2000)
                time.sleep(1.5)
                return True, f"Clicked element [{action.element_id}] using force click"
            except Exception as e2:
                # Try JS click fallback
                try:
                    locator.evaluate("el => el.click()")
                    time.sleep(1.5)
                    return True, f"Clicked element [{action.element_id}] using JavaScript click"
                except Exception as e3:
                    return False, f"Click failed: {str(e3)}"

    def _execute_fill(self, action: AgentAction, elements_map: Dict[str, InteractiveElement]) -> Tuple[bool, str]:
        locator = self._resolve_locator(action, elements_map)
        if not locator:
            return False, f"Could not find input element for target '{action.element_id or action.selector}'"

        text_val = action.value or ""
        try:
            locator.scroll_into_view_if_needed(timeout=3000)
            locator.fill(text_val, timeout=5000)
            time.sleep(0.4)
            mask = '***' if ('pass' in (action.element_id or '').lower() or 'pass' in action.reasoning.lower()) else text_val
            return True, f"Filled [{action.element_id}] with '{mask}'"
        except Exception as e:
            # Fallback to JS fill
            try:
                locator.evaluate(f"el => {{ el.value = '{text_val}'; el.dispatchEvent(new Event('input', {{ bubbles: true }})); el.dispatchEvent(new Event('change', {{ bubbles: true }})); }}")
                time.sleep(0.4)
                return True, f"Filled [{action.element_id}] via JS"
            except Exception as e2:
                return False, f"Fill failed: {str(e2)}"

    def _execute_select(self, action: AgentAction, elements_map: Dict[str, InteractiveElement]) -> Tuple[bool, str]:
        locator = self._resolve_locator(action, elements_map)
        if not locator:
            return False, f"Could not find select dropdown for target '{action.element_id or action.selector}'"

        val = action.value or ""
        try:
            locator.select_option(label=val)
            return True, f"Selected option '{val}' in [{action.element_id}]"
        except:
            try:
                locator.select_option(value=val)
                return True, f"Selected option value '{val}' in [{action.element_id}]"
            except Exception as e:
                return False, f"Select option failed: {str(e)}"

    def _execute_assert(self, action: AgentAction) -> Tuple[bool, str]:
        expected = (action.assertion_condition or action.value or "").strip().lower()
        current_url = self.page.url.lower()
        page_text = self.page.inner_text("body").lower()

        url_match = expected in current_url
        text_match = expected in page_text

        if url_match or text_match:
            location = "URL" if url_match else "Page Content"
            return True, f"Assertion PASSED: Found '{expected}' in {location}"
        else:
            return False, f"Assertion FAILED: Expected '{expected}' was not found in page content or URL"

    def _resolve_locator(self, action: AgentAction, elements_map: Dict[str, InteractiveElement]):
        """Resolves the best Playwright locator for an action."""
        if action.element_id and action.element_id in elements_map:
            el = elements_map[action.element_id]
            # 1. Direct data-agent-id
            loc = self.page.locator(f"[data-agent-id='{action.element_id}']")
            if loc.count() > 0:
                return loc.first
            
            # 2. Name or ID attribute
            if el.name:
                loc_name = self.page.locator(f"[name='{el.name}']")
                if loc_name.count() > 0:
                    return loc_name.first

            # 3. Input type
            if el.input_type in ["email", "password"]:
                loc_type = self.page.locator(f"input[type='{el.input_type}']")
                if loc_type.count() > 0:
                    return loc_type.first

            # 4. Fallback by text if link or button
            if el.text and el.tag in ["button", "a"]:
                loc_txt = self.page.get_by_text(el.text, exact=False)
                if loc_txt.count() > 0:
                    return loc_txt.first

        if action.selector:
            loc = self.page.locator(action.selector)
            if loc.count() > 0:
                return loc.first

        return None
